import re

list_of_units  = ['GPa', 'MPa', 'kPa' 'Pa', 'mPa', 
                    '%',
                    'km', 'm', 'cm', 'mm', 'µm', 'nm', 'um',
                    'kg', 'g', 'gr' 'mg',
                    'hr', 'h', 'sec', 's',
                    '°', '°C', 'F', 'degC',
                    'ppm']

def value_extractor(string):
    original_string = string[:]
    extracted_unit = None
    balance_syn =  ['balance', 'bal', 'bal.', 'other.','other']
    if string.lower() in balance_syn:
        return 'balance', extracted_unit

    units = [u for u in list_of_units if u in string]
    if units:
        extracted_unit = max(units)
        string = string.replace(extracted_unit,'')

    #e.g. already in int or float form: 12.5 -> 12.5
    try:
        return float(string), extracted_unit
    except:
        pass

    #e.g. 12.5 - 13.5 -> 13.0
    range_regex = re.compile('\d+\.?\d*\s*-\s*\d+\.?\d*')
    try:
        ranges = range_regex.search(string).group().split('-')
        average = (float(ranges[0]) + float(ranges[1])) / 2.0
        return average, extracted_unit
    except:
        pass

    #e.g. 12.2 (5.2) -> 12.2
    bracket_regex = re.compile('(\d+\.?\d*)\s*\(\d*.?\d*\)')
    try:
        extracted_value = float(bracket_regex.search(string).group(1))
        return float(extracted_value), extracted_unit
    except:
        pass

    #e.g. 12.3 ± 0.5 -> 12.3
    plusmin_regex = re.compile('(\d+\.?\d*)(\s*[±+-]+\s*\d+\.?\d*)')  
    try:
        extracted_value = float(plusmin_regex.search(string).group(1))
        return extracted_value, extracted_unit
    except AttributeError:
        pass

    #e.g. <0.05 -> 0.05  |  >72.0 -> 72.0    | ~12 -> 12
    lessthan_roughly_regex = re.compile('([<]|[~]|[>])=?\s*\d+\.*\d*')
    try:
        extracted_value = lessthan_roughly_regex.search(string).group()
        num_regex = re.compile('\d+\.*\d*')
        extracted_value = num_regex.search(extracted_value).group()
        return float(extracted_value), extracted_unit
    except:
        pass

    # e.g. 0.4:0.6 (ratios)
    if ':' in string:
        split = string.split(":")
        try:
            extracted_value = round(float(split[0])/float(split[1]), 3)
            return extracted_value, extracted_unit
        except:
            pass
    return original_string, None

def extract_first_number(sentence):
    # Define a regex pattern to match integers and floats
    pattern = r'\b\d+(\.\d+)?\b'
    
    # Search for the first occurrence of the pattern
    match = re.search(pattern, sentence)
    
    if match:
        # Extract the matched number and convert it to float
        number = match.group(0)
        return float(number)
    else:
        return 0

def make_hill(chemicals):
    '''
    Function for converting chemical formula to hill notation.
    Takes input as a list of chemical formulas, e.g.,
    
    >> chemicals = ['Al2O3', 'C12A7']
    >> make_hill(chemicals)
    Output: ['Al$_2$O$_3$', 'C$_{12}$A$_7$']
    '''
    
    hill_all = []
    
    for col in chemicals:
        # Use regular expression to find elements and their subscripts
        hill = re.sub(r'([A-Za-z])(\d+)', r'\1$_{\2}$', col)  # Convert subscripts
        hill_all.append(hill)
    
    return hill_all

def nzcols(df5):
    return (df5.T[df5.astype(bool).sum(axis=0).astype(bool)]).T

